package utils

import (
	"net"
	"log"
)

/* +---------------------------------------------------------------------+ */
/* |                             Fonctions                               | */
/* +---------------------------------------------------------------------+ */

func ServerWrite(conn net.Conn, message string) {
    _, err := conn.Write([]byte(message)) 
    if err != nil {
        log.Printf("Server write error: %v", err)
    }
}