/* ----------------------------------------------------------------------- */
/*                               Structure                                 */
/* ----------------------------------------------------------------------- */

pub struct Item<'a> {
    pub id: u16,
    pub name: &'a str,
    pub description_fr: &'a str,
    pub description_en: &'a str,
    pub nb_copies: i16,
    pub nb_avail: i16,
}

/* ----------------------------------------------------------------------- */
/*                                Méthodes                                 */
/* ----------------------------------------------------------------------- */

impl<'a> Item<'a> {
    /* ------------------------------------------------------------------- */
    /*                                Méthodes                             */
    /* ------------------------------------------------------------------- */

    pub fn new(
        id: u16,
        name: &'a str,
        description_fr: &'a str,
        description_en: &'a str,
        nb_copies: i16,
        nb_avail: i16,
    ) -> Self {
        Self {
            id,
            name,
            description_fr,
            description_en,
            nb_copies,
            nb_avail,
        }
    }

    /* ------------------------------------------------------------------- */
    /*                             Modificateurs                           */
    /* ------------------------------------------------------------------- */

    pub fn set_nb_avail(&mut self, new_value: i16) {
        self.nb_avail = new_value;
    }
}
