use serde::Deserialize;

/* ----------------------------------------------------------------------- */
/*                               Structure                                 */
/* ----------------------------------------------------------------------- */

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Loot {
    pub id: u16,
    pub name: String,
    pub description_fr: String,
    pub description_en: String,
    pub cost: u16,
    pub nb_copies: i16,
    pub nb_avail: i16,
}

/* ----------------------------------------------------------------------- */
/*                                Méthodes                                 */
/* ----------------------------------------------------------------------- */

impl Loot {

    /* ------------------------------------------------------------------- */
    /*                             Modificateurs                           */
    /* ------------------------------------------------------------------- */

    pub fn set_nb_avail(&mut self, new_value: i16) {
        self.nb_avail = new_value;
    }
}
