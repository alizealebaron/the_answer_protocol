use crate::models::item_model::Item;

/* ----------------------------------------------------------------------- */
/*                               Structure                                 */
/* ----------------------------------------------------------------------- */

pub struct Edible<'a> {
    pub item: Item<'a>,
    pub effect: &'a str,
    pub var_nb: i16
}

/* ----------------------------------------------------------------------- */
/*                                Méthodes                                 */
/* ----------------------------------------------------------------------- */

impl<'a> Edible<'a> {

    /* ------------------------------------------------------------------- */
    /*                              Constructeur                           */
    /* ------------------------------------------------------------------- */

    pub fn new(
        item: Item<'a>,
        effect: &'a str,
        var_nb: i16,
    ) -> Self {
        Self {
            item,
            effect,
            var_nb,
        }
    }
}
