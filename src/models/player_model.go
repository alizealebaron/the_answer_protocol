var totalPlayer int

/* +---------------------------------------------------------------------+ */
/* |                                Item                                 | */
/* +---------------------------------------------------------------------+ */

type Player struct {
	Id       int
    Name     string
    Pv       int
    Attack   int
    Language string
    Inventory []Item 
}

func NewPlayer(name string, language string) Player {

    lstItem := []Item{}
    player := Player{totalPlayer, name, 100, 5, language, lstItem}
    totalPlayer += 1
    return player
}
